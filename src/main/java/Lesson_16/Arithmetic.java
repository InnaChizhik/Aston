package Lesson_16;

public class Arithmetic {
    public static int plus(int a, int b) {
        return a + b;
    }

    public static int minus(int a, int b) {
        return a - b;
    }

    public static int multiply(int a, int b) {
        return a * b;
    }

    public static double del(int a, int b) {
        return a / b;
    }
}
